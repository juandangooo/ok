"""Hellhound Audio - glyph sources.

Caps-only display face.  Every glyph is a pile of heavy bars and wedges; the
chamfer pass in geom.py cuts the corners afterwards, which is where the
chiselled look comes from.  Lowercase codepoints map to the caps.

Design space: 1000 upm, baseline 0, cap height 700, descender -140.
"""

