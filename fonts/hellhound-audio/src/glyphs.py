# Every entry: name -> (advance, [solids], [holes], [(solids, holes), ...])
# The trailing groups are unioned on *after* the holes are punched, which is how
# a shape can sit inside a counter (the middle of @, for instance).
GLYPHS = {}


def g(name, advance, solids, holes=(), extra=()):
    GLYPHS[name] = (advance, solids, list(holes), [(list(a), list(b)) for a, b in extra])


